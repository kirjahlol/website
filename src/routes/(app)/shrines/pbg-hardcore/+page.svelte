<section>
	<h3>About</h3>
	<p>
		<b>Hardcore</b> is a web series hosted by YouTuber Austin Hargrave, also known as
		PeanutButterGamer and just PBG. The series was co-founded by PBG and his brother,
		<span class="blur-sm">Stewart Hargrave (McJones)</span>, in 2012 and began with the release of
		the first season Minecraft #1 (release spanning from July 23rd, 2012 to September 27th, 2012).
	</p>
	<p>
		The premise of the series is that a group of players (typically 7) work together to accomplish a
		goal in a videogame, with the catch being that if a player dies at any point during the game,
		they can not come back and are eliminated from the series. Players also can not talk after they
		are eliminated as to not interfere with the immersion of the viewer.
	</p>
	<p>
		In the original Hardcore series, the main cast members were PBG, Jeff Fabre (SpaceHamster), Dean
		Elazab, and Barry Kramer. <span class="blur-sm">McJones</span> and Jared Knabenbauer (ProJared)
		were former mains. The series also featured a variety of guests, including
		<span class="blur-sm">Jon Jafari (JonTron)</span>, Ross O'Donovan (RubberRoss), and Jim Caddick
		(Caddicarus).
	</p>
	<p>
		There were a total of 15 full-length seasons in the original Hardcore series: 7 Minecraft
		seasons, 3 Terraria seasons, 2 MineZ seasons, 1 DayZ season, 1 Diablo II season, and 1 Starbound
		season. There was also 1 mini season: Mount & Blade Napoleonic Wars.
	</p>
	<p>
		For the first 5 seasons, PBG was the main video editor of the series. This changed with the
		release of Mincraft #3, which is when SpaceHamster became the editor. After Minecraft #4
		finished its release in May of 2015, the series went on a nearly 2 year hiatus, returning in
		December of 2016 with the release of Minecraft #5. This return brought on some major changes to
		the series, most notably a change in editors from Jeff to Todd Cameron (who, as of now, has
		edited all of the seasons past Minecraft #4) and the introduction of drawn portraits for the
		cast members by the artist Krooked Glasses. The last season released in the original Hardcore
		series was Minecraft #7 (release spanning from November 23rd, 2018 to January 12th, 2019). After
		Minecraft #7 finished its release, the series went on another 2 year hiatus.
	</p>
	<p>
		On May 19th, 2021, in a video titled "Minecraft - PBG," PBG announced both that the Hardcore
		series would be returning on the NormalBoots YouTube channel and a new season was releasing,
		that season being NB Minecraft #1 (release spanning from May 19th, 2021 to July 10th, 2021).
		Since the end of NB Minecraft #1, no further Hardcore seasons have been released. Given the
		status of NormalBoots and the fact that PBG has become a father since the end of the last
		season, it is unlikely that the series will return soon or even ever, though PBG has hinted at a
		return in the past.
	</p>
</section>
